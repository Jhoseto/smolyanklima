-- Помощна функция: вмъква доставчик + телефоните му САМО ако още няма
-- contact_kind='supplier' с такова име (case-insensitive). Връща UUID-а
-- на новосъздадения контакт; ако вече съществува — връща NULL.
--
-- p_phones е масив от записи „телефон|етикет" (разделител = вертикална
-- черта). Първият елемент се счита за „основен" телефон и се записва и
-- в contacts.phone. ВСИЧКИ елементи се добавят в contact_phones.
create or replace function pg_temp.upsert_supplier(
  p_full_name text,
  p_phones    text[],
  p_email     text,
  p_address   text,
  p_notes     text
) returns uuid
language plpgsql as $$
declare
  v_contact_id uuid;
  v_pair       text;
  v_phone      text;
  v_label      text;
  v_idx        int := 0;
  v_primary    text;
begin
  if exists (
    select 1 from public.contacts
    where contact_kind = 'supplier'
      and upper(btrim(full_name)) = upper(btrim(p_full_name))
  ) then
    -- Доставчикът вече съществува — нищо не правим, за да не презаписваме
    -- ръчно нанесените корекции.
    return null;
  end if;

  if p_phones is null or array_length(p_phones, 1) is null then
    raise exception 'Доставчик % няма телефони — нужен е поне един.', p_full_name;
  end if;

  -- Първият елемент е основният телефон. Може да съдържа етикет след „|".
  v_pair := p_phones[1];
  v_phone := split_part(v_pair, '|', 1);
  v_primary := btrim(v_phone);

  insert into public.contacts (
    full_name, phone, email, address, notes, contact_kind
  ) values (
    p_full_name, v_primary, p_email, p_address, p_notes, 'supplier'
  )
  returning id into v_contact_id;

  -- Запис на ВСИЧКИ телефони (вкл. основния) в contact_phones.
  foreach v_pair in array p_phones loop
    v_phone := btrim(split_part(v_pair, '|', 1));
    v_label := nullif(btrim(split_part(v_pair, '|', 2)), '');
    if length(v_phone) >= 3 then
      insert into public.contact_phones (
        contact_id, phone, label, is_primary, sort_order
      ) values (
        v_contact_id, v_phone, v_label, (v_idx = 0), v_idx
      );
    end if;
    v_idx := v_idx + 1;
  end loop;

  return v_contact_id;
end;
$$;

