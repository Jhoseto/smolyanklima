-- 0005_clear_aerf_client_notes.sql
-- Изпразва бележките на ВСИЧКИ клиенти (contact_kind = 'client').
--
-- Контекст: първоначалната версия на seed 0004 записваше история на
-- продажбите в `contacts.notes`. След това решихме този подход да отпадне —
-- историята се води оперативно през UI-то, а полето „бележки" трябва да
-- остане празно за всички клиенти, готово оператор да добави свободен
-- текст при нужда.
--
-- ВАЖНО: UI-то за редакция на бележки остава функционално (виж
-- /admin/contacts → поле „Бележки"). Този скрипт само reset-ва текущите
-- стойности до NULL.
--
-- ОБХВАТ:
--   * Само контакти с contact_kind = 'client'. Доставчиците не се пипат.
--   * Идемпотентно — повторно изпълнение не прави нищо.
--
-- Изпълнение: копирай в Supabase SQL Editor → Run.

UPDATE public.contacts
SET notes = NULL
WHERE contact_kind = 'client'
  AND notes IS NOT NULL;
